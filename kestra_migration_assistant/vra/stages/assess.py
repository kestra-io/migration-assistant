"""
Stage 1, Assess (code only).

Runs the parser, call graph, fingerprints and clusters, on a fresh output directory (stages/1-assess/work). Adds:

- the target inventory (targets.py),
- wrapper and library detection,
- the list of nested calls whose target is not in the export,
- domains: clusters grouped by primary target and lifecycle stage.

The grouping into domains is decided here, in code, and recorded per cluster.
Only the domain names come from the model, in one cached call, and only from
the cached cluster summaries. With VRO_NO_MODEL=1 the names fall back to
"<target> <stage>".
"""
