def _detected_by(o: dict) -> str | None:
    """How an operation was attributed to its system: a vRO plugin's objects, or a REST call named by the
    system's API signature (a path or a header)."""
    if o.get("evidence") is not None or o.get("helper"):
        return "REST signature (" + ", ".join(o.get("evidence") or ["the REST helper's call site"]) + ")"
    if o.get("kind") in ("rest-host", "rest", "rest client") and o.get("target") == "rest-host":
        return "REST request"
    if o.get("kind") == "unexported workflow":
        return "plugin library workflow"
    if o.get("target") == "vro-platform":
        return "vRO platform call"
    return "plugin"


AUTH_SIGNS = [("basic authentication", re.compile(r"\bBasic\b|createAuthentication\(\s*[\"']Basic", re.I)),
              ("a bearer token", re.compile(r"\bBearer\b")),
              ("a session login", re.compile(r"/login\b|/session\b|X-CSRFToken|sessionid", re.I))]
TLS_OFF = re.compile(r"hostVerification\s*=\s*false|setHostVerification\(\s*false|ignoreCertificate|"
                     r"trustAll|rejectUnauthorized\s*:\s*false|verifyHost(?:name)?\s*=\s*false|ignoreSSL", re.I)


def _client_auth(client: list[dict]) -> str | None:
    """How the hand-written client for a system authenticates, from its code (and its REST helper's)."""
    text = "\n".join(a.get("script") or "" for a in client)
    found = [name for name, rx in AUTH_SIGNS if rx.search(text)]
    return " and ".join(found) or None


def _tls_off(client: list[dict]) -> str | None:
    """The statement that turns certificate checking off in the client's code, if one does."""
    for a in client:
        m = TLS_OFF.search(a.get("script") or "")
        if m:
            return f"`{m.group(0)}` in {a['name']}"
    return None


# A short tag in front of a workflow name ("LB - Create ...", "[NET] Add ...", "ops: Get ...") says
# which group it belongs to, not what it does; the verb after it decides the stage.
NAME_TAG = re.compile(r"^\s*(?:\[[^\]]{1,16}\]\s*|[\w.]{1,12}\s*[-:|]\s+)")


def _stage_of(name: str) -> str:
    n = NAME_TAG.sub("", name).strip().lower()
    for stage, rx in STAGE_RULES:
        if re.search(rx, n):
            return stage
    return "operations"


def _domains(cres, wf, tinv, summaries, ov) -> dict:
    """Group clusters by (primary target, lifecycle stage). Code decides; the model only names."""

    def op_targets(u, seen=None):
        """Target operations of a workflow and, failing that, of the exported workflows it calls."""
        seen = seen or set()
        if u in seen or u not in wf:
            return Counter()
        seen.add(u)
        cnt = Counter()
        for o in wf[u]["ops"]:
            t = o["target"]
            if t == "vro-platform" and "Avi" in o["op"]:
                t = "avi-controller"          # Avi endpoint registration and client lookups
            if t != "vro-platform":
                cnt[t] += 1
        if not cnt:
            for n in wf[u]["nested"]:
                if n.get("target_uid"):
                    cnt += op_targets(n["target_uid"], seen)
        return cnt

    rows = []
    for c in cres["clusters"]:
        with_ops: Counter[str] | dict[str, int] = Counter()
        basis = "own operations"
        for u in c["members"]:
            with_ops += op_targets(u)
        if not with_ops:
            for u in c["members"]:
                for t in wf[u]["declared_targets"]:
                    with_ops[t] += 1
            basis = "declared plugin types"
        with_ops = {k: v for k, v in with_ops.items() if v > 0}
        primary = max(sorted(with_ops), key=lambda k: with_ops[k]) if with_ops else None
        stages = Counter(_stage_of(wf[u]["name"]) for u in c["members"])
        top = stages.most_common()
        if len(top) > 1 and top[0][1] == top[1][1]:
            stage = _stage_of(wf[c["first_of_a_kind"]]["name"])
            stage_how = f"tie {dict(stages)}; first of a kind '{wf[c['first_of_a_kind']]['name']}' decides"
        else:
            stage = top[0][0]
            stage_how = f"member names {dict(stages)}"
        fams = Counter(_family(wf[u]["source"]) for u in c["members"])
        family = fams.most_common(1)[0][0]
        if primary is None or basis == "declared plugin types":
            key = "none:fixtures"
            how = ("no operation against any external system in any member or its exported callees"
                   + (f" (declares {sorted(with_ops)} types only)" if with_ops else ""))
        else:
            key = f"{family}:{stage}"
            how = (f"source {family}; talks to {primary} ({with_ops[primary]} of {sum(with_ops.values())} "
                   f"target operations, own or through exported callees); stage from {stage_how}")
        rows.append({"cluster_id": c["cluster_id"], "key": key, "how": how,
                     "primary_target": None if key == "none:fixtures" else primary,
                     "stage": "fixtures" if key == "none:fixtures" else stage})

    moves = (ov.get("domains") or {}).get("move") or {}
    for r in rows:
        if r["cluster_id"] in moves:
            r["key"] = moves[r["cluster_id"]]
            r["how"] += f"; moved to {r['key']} in corrections.yaml"

    by_key = defaultdict(list)
    for r in rows:
        by_key[r["key"]].append(r["cluster_id"])

    stage_order = {"provisioning": 0, "configuration": 1, "operations": 2, "fixtures": 3}
    keys = sorted(by_key, key=lambda k: (k == "none:fixtures", k.split(":")[0], stage_order.get(k.split(":")[1], 9)))
    names = _name_domains(keys, by_key, cres, summaries, tinv)
    renames = (ov.get("domains") or {}).get("rename") or {}
    doms = []
    for i, k in enumerate(keys, 1):
        members = by_key[k]
        n_wf = sum(len(next(c for c in cres["clusters"] if c["cluster_id"] == cid)["members"]) for cid in members)
        tgt, stg = k.split(":")
        doms.append({
            "id": f"D{i}", "key": k, "family": None if tgt == "none" else tgt, "stage": stg,
            "targets": sorted({r["primary_target"] for r in rows if r["key"] == k and r["primary_target"]}),
            "name": renames.get(k) or names.get(k, {}).get("name") or _fallback_name(
                k, tinv, [wf[u] for cid in members for u in
                          next(c for c in cres["clusters"] if c["cluster_id"] == cid)["members"]],
                sorted({t for cid in members for u in next(c for c in cres["clusters"]
                                                           if c["cluster_id"] == cid)["members"]
                        for t in wf[u]["targets"]})),
            "description": names.get(k, {}).get("description"),
            "name_source": "corrections.yaml" if k in renames else
                           ("model (cached cluster summaries)" if k in names else "code fallback"),
            "clusters": members, "workflows": n_wf,
        })
    return {"rule": "source package family x lifecycle stage (majority of member names by verb: "
                    + "; ".join(f"{s}: {rx}" for s, rx in STAGE_RULES)
                    + "). A cluster whose members and their exported callees make no call to an external "
              "system goes to fixtures. The cluster's primary target (most operations, vRO platform "
              "excluded) is recorded alongside.",
            "domains": doms, "cluster_rows": rows,
            "cluster_domain": {r["cluster_id"]: next(d["id"] for d in doms if d["key"] == r["key"]) for r in rows}}


FAMILY_LABEL = {"alb": "Avi load balancer", "vspk": "Nuage networking", "pkgdiff": "package tests",
                "canvas": "canvas tests", "aria-xml": "build tools sample"}


def _family(source: str) -> str:
    """pkgdiff-v1.0 and pkgdiff-v1.1 are one package family."""
    return re.sub(r"-v\d+(\.\d+)*$", "", source)


NAME_STOP = {"a", "an", "and", "the", "to", "from", "of", "in", "on", "for", "with", "by", "or", "at", "into",
             "vro", "workflow", "workflows", "test", "new", "all", "via"}
VERBS = re.compile(r"^(create|add|delete|remove|get|set|update|edit|change|list|find|run|process|send|check|"
                   r"assign|attach|detach|enable|disable|install|deploy|instantiate|reconfigure|scale|"
                   r"setup|configure|register|unregister|start|stop|restart|power|clone|move|rename|sync|"
                   r"import|export|execute|invoke|build|make|handle|clean|cleanup|validate)$")


def _topic(names: list[str], categories: list[str], sources: Sequence[str] = ()) -> str | None:
    """What the members' own names have in common, without verbs and tags: a word pair or a word
    shared by at least two members, else the last part of their shared folder. Among equally common
    candidates, one that also appears in the folder or package name wins."""
    where = re.sub(r"[^a-z0-9]", "", " ".join(list(categories) + list(sources)).lower())
    toks = []
    for n in names:
        words = [w for w in re.findall(r"[A-Za-z][A-Za-z0-9]+", NAME_TAG.sub("", n).lower())
                 if w not in NAME_STOP and not VERBS.match(w)]
        toks.append(words)
    need = 2 if len(names) > 1 else 1
    pairs = Counter(p for ws in toks for p in {f"{a} {b}" for a, b in zip(ws, ws[1:], strict=False)})
    def pick(counter, ok):
        cands = [(c, k.replace(" ", "") in where, k) for k, c in counter.items() if c >= need and ok(k)]
        return max(cands, key=lambda x: (x[0], x[1]))[2] if cands else None
    best = pick(pairs, lambda k: True) or pick(Counter(w for ws in toks for w in set(ws)), lambda k: len(k) > 2)
    if best:
        return best
    cats = {c for c in categories if c}
    if len(cats) == 1:
        last = re.split(r"[/.]", cats.pop())[-1]
        return re.sub(r"(?<=[a-z])(?=[A-Z])", " ", last).lower() or None
    return None


def _fallback_name(key: str, tinv: dict, members: list[dict] | None = None,
                   targets: list[str] | None = None) -> str:
    """A neutral name from the domain's own content, used when no model named it: what the member
    names share, and the systems it talks to."""
    members = members or []
    topic = _topic([w["name"] for w in members], [w.get("category_path") or "" for w in members],
                   sorted({w.get("source") or "" for w in members}))
    tnames = [re.sub(r"\s*\(.*\)$", "", (tinv.get(t) or {}).get("short_name") or (tinv.get(t) or {}).get("name") or t)
              for t in (targets or []) if t != "vro-platform"]
    head = f"{topic[0].upper()}{topic[1:]} workflows" if topic else f"Workflow group ({len(members)})"
    if tnames:
        return f"{head} ({', '.join(tnames[:3])})"
    return f"{head} (no external system found)" if key.startswith("none:") else head


def domain_names_prompt(payload: list[dict]) -> str:
    return safety.guard(
        "You are naming groups of VMware vRealize Orchestrator workflows for a migration report read by a "
        "platform lead. The grouping is already decided and must not change. For each domain below, write a "
        "short name (2 to 5 words, plain language, no marketing words, no em dashes) and one plain sentence "
        "saying what the workflows in it do. Use only what the cluster summaries say.\n\n"
        + safety.wrap("domains and cluster summaries", json.dumps(payload, indent=1)))


def _name_domains(keys, by_key, cres, summaries, tinv) -> dict:
    """One model call: a short name and one sentence per domain, from cached cluster summaries."""
    if os.environ.get("VRO_NO_MODEL"):
        cached = os.path.join(C.ASSESS, "domain-names.json")
        return C.read_json(cached).get("names", {}) if os.path.exists(cached) else {}
    payload = []
    for k in keys:
        payload.append({
            "domain_key": k,
            "source_package": None if k.startswith("none:") else FAMILY_LABEL.get(k.split(":")[0], k.split(":")[0]),
            "lifecycle_stage": k.split(":")[1],
            "clusters": [{"cluster": cid, "summary_name": (summaries.get(cid) or {}).get("name"),
                          "summary": ((summaries.get(cid) or {}).get("what_the_group_does") or "")[:500]}
                         for cid in by_key[k]],
        })
    prompt = domain_names_prompt(payload)
    schema = {"type": "object", "additionalProperties": False, "required": ["domains"],
              "properties": {"domains": {"type": "array", "items": {
                  "type": "object", "additionalProperties": False,
                  "required": ["domain_key", "name", "description"],
                  "properties": {"domain_key": {"type": "string"}, "name": {"type": "string"},
                                 "description": {"type": "string"}}}}}}
    try:
        M = C.model()
        v = M.ask("stages-domain-names", "estate", prompt, schema)
    except Exception as e:
        print(f"[assess] domain naming fell back to code labels: {e}")
        return {}
    names = {d["domain_key"]: {"name": C.no_em_dashes(d["name"]), "description": C.no_em_dashes(d["description"])}
             for d in v["domains"] if d["domain_key"] in keys}
    C.write_json(os.path.join(C.ASSESS, "domain-names.json"), {"names": names, "prompt_domains": keys})
    return names


def cluster_summaries(clusters: list[dict]) -> dict:
    """
    The model-written summary per cluster, from `2-understand/cluster-summaries.json` (written by
    Understand). Matched by member set, not cluster id, so a renumbered cluster keeps its
    summary and a cluster whose members changed gets none rather than the wrong one.
    """
    if not os.path.exists(C.CLUSTER_SUMMARIES):
        return {}
    by_members = {tuple(sorted(v.get("members") or [])): v for v in C.read_json(C.CLUSTER_SUMMARIES).values()}
    return {c["cluster_id"]: by_members[tuple(sorted(c["members"]))]
            for c in clusters if tuple(sorted(c["members"])) in by_members}


